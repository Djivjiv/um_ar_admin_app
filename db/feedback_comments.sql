-- ===========================================================================
-- Suggestions and comments, written by the user app, read by the admin app's
-- "Suggestions & Comments" screen.
-- Run in the Supabase SQL editor. Safe to re-run. Needs public.is_admin(),
-- from db/user_roles.sql.
--
-- The user app writes this table, and its supabase/feedback_comments.sql is a
-- copy of this file: run one of the two. Until a comment arrives, the screen
-- shows "No data yet".
--
-- Do not add name or email columns. The admin screen shows only the role and
-- a short anonymous id made from user_id, else device_code.
-- ===========================================================================

create table if not exists public.feedback_comments (
  id              bigint generated by default as identity primary key,
  comment         text not null,
  -- Optional, e.g. "4 of 5 after navigating to the Library".
  rating_context  text,
  -- student, faculty, employee, visitor. Free text so a new role can't fail
  -- the user app's insert.
  role            text,
  -- Set device_code for visitors, user_id when signed in.
  device_code     text,
  user_id         uuid,
  created_at      timestamptz not null default now()
);

create index if not exists feedback_comments_created_at_idx
  on public.feedback_comments (created_at desc);

-- The app may only INSERT. Visitors use the anon key (user_id must be null);
-- signed-in users may only write rows for themselves. Admins may read.
alter table public.feedback_comments enable row level security;

drop policy if exists "app insert feedback_comments" on public.feedback_comments;
create policy "app insert feedback_comments"
  on public.feedback_comments for insert
  to anon, authenticated
  with check (user_id is null or user_id = auth.uid());

drop policy if exists "admin read feedback_comments" on public.feedback_comments;
create policy "admin read feedback_comments"
  on public.feedback_comments for select
  to authenticated
  using (public.is_admin());

-- Make the new table visible to PostgREST immediately.
notify pgrst, 'reload schema';
