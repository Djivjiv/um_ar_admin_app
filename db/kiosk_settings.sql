-- ===========================================================================
-- kiosk_settings: the one settings row the kiosk tablet reads (admin app
-- Kiosk Management > Settings). Run in the Supabase SQL editor. Safe to
-- re-run: it only creates what is missing and never changes existing values.
--
-- RUN THIS BEFORE db/kiosk_management.sql, which inserts the first row, and
-- before the kiosk app's kiosk_settings_read.sql and kiosk_exit_pin.sql.
-- No other file creates this table.
--
-- Columns, and who reads them:
--   id                    admin app, kiosk (first row by id)
--   welcome_message       admin app, kiosk
--   disclaimer_text       admin app, kiosk
--   app_download_url      admin app, kiosk (shown as a QR code)
--   idle_timeout_seconds  admin app (30 to 300), kiosk
--   is_survey_enabled     admin app, kiosk
--   announcement_text     admin app, kiosk
--   updated_at            admin app
--   exit_pin              kiosk staff screen. The admin app only writes it.
--
-- exit_pin: 4 to 12 digits, the same rule as the kiosk app's
-- kiosk_exit_pin.sql (same constraint name, so either file may run first).
-- The admin app's PIN field accepts 4 to 8 digits. Null = no PIN, and the
-- kiosk exit stays locked. This file sets no PIN: set it in the admin app.
--
-- Row Level Security is set by db/admin_lockdown.sql. Until that has run,
-- whatever policies the table already has stay in place.
-- ===========================================================================

create table if not exists public.kiosk_settings (
  id                   bigint generated by default as identity primary key,
  welcome_message      text,
  disclaimer_text      text,
  app_download_url     text,
  idle_timeout_seconds integer not null default 120,
  is_survey_enabled    boolean not null default true,
  announcement_text    text,
  updated_at           timestamptz not null default now(),
  exit_pin             text
);

-- The table may already exist without some of these columns.
alter table public.kiosk_settings add column if not exists welcome_message      text;
alter table public.kiosk_settings add column if not exists disclaimer_text      text;
alter table public.kiosk_settings add column if not exists app_download_url     text;
alter table public.kiosk_settings add column if not exists idle_timeout_seconds integer default 120;
alter table public.kiosk_settings add column if not exists is_survey_enabled    boolean default true;
alter table public.kiosk_settings add column if not exists announcement_text    text;
alter table public.kiosk_settings add column if not exists updated_at           timestamptz default now();
alter table public.kiosk_settings add column if not exists exit_pin             text;

alter table public.kiosk_settings
  drop constraint if exists kiosk_settings_exit_pin_format;
alter table public.kiosk_settings
  add constraint kiosk_settings_exit_pin_format
  check (exit_pin is null or exit_pin ~ '^[0-9]{4,12}$');

-- Make the table visible to PostgREST immediately.
notify pgrst, 'reload schema';
